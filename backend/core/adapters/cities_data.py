def nearest_city(lat, lon):
    """Returns (label, lat, lon) for the closest bundled city, using a
    flat-earth approximation (good enough at highway-fallback precision)."""
    best = None
    best_dist_sq = None
    for name, state, city_lat, city_lon in US_CITIES:
        dist_sq = (city_lat - lat) ** 2 + (city_lon - lon) ** 2
        if best_dist_sq is None or dist_sq < best_dist_sq:
            best_dist_sq = dist_sq
            best = (f"{name}, {state}", city_lat, city_lon)
    return best
